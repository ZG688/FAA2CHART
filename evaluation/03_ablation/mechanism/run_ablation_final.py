def _dict_to_prose(res: Any) -> str:
    if not isinstance(res, dict):
        return str(res)
    parts = []
    if res.get("step"):
        parts.append(f"I just completed step {res['step']}.")
    if res.get("job_id"):
        parts.append(f"The current job ID is {res['job_id']}.")
    summary = res.get("summary")
    if isinstance(summary, dict):
        for k, v in summary.items():
            parts.append(f"{k} is now {v}.")
    elif summary is not None:
        parts.append(f"Task summary: {summary}.")
    if res.get("ok"):
        parts.append("This step executed successfully.")
    return " ".join(parts) if parts else json.dumps(res, ensure_ascii=False)


def _wrap_tools_nl(tools: List) -> List:
    wrapped = []
    for t in tools:
        def _make_runner(orig):
            def _runner(**kwargs):
                return _dict_to_prose(orig.invoke(kwargs))
            return _runner
        wrapped.append(StructuredTool(
            name=t.name, description=t.description,
            args_schema=t.args_schema, func=_make_runner(t),
        ))
    return wrapped


