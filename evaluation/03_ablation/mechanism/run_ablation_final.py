def build_agent_for_variant(variant: str, model):
    """Returns (agent, is_single)."""
    if variant in ("single", "single_serial"):
        # Single agent: all tools combined into one agent, no supervisor / no sub-agents.
        # The prompt directly uses the official domap SINGLE_AGENT_PROMPT — it is a complete
        # workflow prompt specifically written for the single agent, containing stage decision rules,
        # JSON path hard rules, cartography stage order constraints, and result checking requirements.
        # Using the official implementation avoids the criticism of "the baseline was artificially weakened".
        #
        # single        —— default config, multiple tool_calls in the same round executed concurrently by ToolNode
        # single_serial —— force serial execution (see max_concurrency=1 in run_one)
        #                  used to separate "parallel race conditions" from "architectural defects" as failure sources
        seen, tools = set(), []
        for t in ([parse_doc_tool, find_file_by_name_tool,
                   update_airway_coordinates_tool, choose_final_json_path_tool]
                  + get_deepagent_job_tools() + get_layer_loader_job_tools()
                  + get_spatial_analysis_job_tools() + get_map_decoration_job_tools()):
            if t.name not in seen:
                seen.add(t.name); tools.append(t)
        return _mk_agent(model, tools, SINGLE_AGENT_PROMPT), True

    if variant == "control":
        return _build_supervisor(model, build_subagents_control(model)), False
    if variant == "A_merge":
        return _build_supervisor(model, build_subagents_A(model)), False
    if variant == "C_natural_lang":
        return _build_supervisor_C(model, build_subagents_C(model)), False
    if variant == "D_no_guard":
        return _build_supervisor(model, build_subagents_D(model),
                                 supervisor_prompt=_strip_guard_lines(SUPERVISOR_PROMPT)), False
    if variant == "B_no_store":
        _patch_no_store()
        return _build_supervisor(model, build_subagents_control(model)), False
    raise ValueError(f"Unknown variant: {variant}")


# Backup of B_no_store's original implementations, used for restoration (avoid contaminating subsequent variants)
_ORIG_CREATE_JOB = None
_ORIG_GET_JOB_STATE = None
_ORIG_SAVE_JOB_STATE = None


def _patch_no_store():
    """Ablation B: Replace runtime_job_store with "in-dialogue JSON serialization" storage.
    QGIS objects cannot be serialized -> expected structural failure, serving as necessity evidence for P2 principle.

    Note: This function modifies module-level function pointers (monkey-patch).
    After calling, _restore_store() must be called to restore, otherwise all subsequent variants will be contaminated.
    """
    global _ORIG_CREATE_JOB, _ORIG_GET_JOB_STATE, _ORIG_SAVE_JOB_STATE
    import domap.connectivity.runtime_job_store as RJS
    from domap.connectivity.shared_map_state import make_initial_state
    import uuid
    # Save original implementations
    _ORIG_CREATE_JOB = RJS.create_job
    _ORIG_GET_JOB_STATE = RJS.get_job_state
    _ORIG_SAVE_JOB_STATE = RJS.save_job_state

    _BLOB: Dict[str, str] = {}

    def create_job(cfg):
        jid = str(uuid.uuid4())
        _BLOB[jid] = json.dumps(make_initial_state(cfg), default=str)
        return jid

    def get_job_state(jid):
        return json.loads(_BLOB[jid])

    def save_job_state(jid, state):
        _BLOB[jid] = json.dumps(state, default=str)

    RJS.create_job = create_job
    RJS.get_job_state = get_job_state
    RJS.save_job_state = save_job_state
    print("WARNING [B_no_store] Switched to in-dialogue serialization storage (expected structural failure)")


def _restore_store():
    """Restore runtime_job_store original implementations, eliminating B_no_store contamination."""
    global _ORIG_CREATE_JOB, _ORIG_GET_JOB_STATE, _ORIG_SAVE_JOB_STATE
    if _ORIG_CREATE_JOB is None:
        return
    import domap.connectivity.runtime_job_store as RJS
    RJS.create_job = _ORIG_CREATE_JOB
    RJS.get_job_state = _ORIG_GET_JOB_STATE
    RJS.save_job_state = _ORIG_SAVE_JOB_STATE
    _ORIG_CREATE_JOB = _ORIG_GET_JOB_STATE = _ORIG_SAVE_JOB_STATE = None
    print("OK [B_no_store] Restored original object store implementation")


# ==================================================================
# Metric collection
# ==================================================================
def _collect_metrics(chunks: List[Dict[str, Any]]) -> Dict[str, Any]:
    total_steps = len(chunks)
    tool_calls = subagent_delegations = tool_errors = ai_messages = 0
    produced_layout = produced_analysis = False
    for chunk in chunks:
        if not isinstance(chunk, dict):
            continue
        for _node, data in chunk.items():
            if not isinstance(data, dict):
                continue
            msgs = data.get("messages")
            if not msgs:
                continue
            seq = msgs.value if hasattr(msgs, "value") else msgs
            for m in (seq or []):
                mtype = getattr(m, "type", "")
                tcs = getattr(m, "tool_calls", None)
                if tcs:
                    tool_calls += len(tcs)
                    for tc in tcs:
                        name = tc.get("name") if isinstance(tc, dict) else getattr(tc, "name", "")
                        if name == "task":
                            subagent_delegations += 1
                if mtype == "tool":
                    status = getattr(m, "status", None)
                    content = str(getattr(m, "content", ""))
                    if status == "error" or "Error" in content or "Traceback" in content:
                        tool_errors += 1
                    if "layout" in content and ("map_item" in content or "layout_name" in content):
                        produced_layout = True
                    if "rows" in content or "summary" in content or "visible_layers" in content:
                        produced_analysis = True
                if mtype == "ai":
                    ai_messages += 1
    return {
        "total_steps": total_steps, "tool_calls": tool_calls,
        "subagent_delegations": subagent_delegations, "tool_errors": tool_errors,
        "ai_messages": ai_messages,
        "produced_layout": produced_layout, "produced_analysis": produced_analysis,
    }


