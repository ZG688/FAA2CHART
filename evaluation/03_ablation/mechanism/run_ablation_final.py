def _sub_event(model):
    return CompiledSubAgent(name="event_extract", description="Event extraction",
        runnable=_mk_agent(model, [parse_doc_tool], EVENT_EXTRACT_PROMPT))


def _sub_geocode(model):
    return CompiledSubAgent(name="geocode", description="Geocoding",
        runnable=_mk_agent(model, [find_file_by_name_tool, update_airway_coordinates_tool], GEOCODE_PROMPT))


def build_subagents_control(model):
    return [
        _sub_event(model), _sub_geocode(model),
        CompiledSubAgent(name="layer_loader", description="Layer loading",
            runnable=_mk_agent(model, get_layer_loader_job_tools(), LAYER_LOADER_PROMPT)),
        CompiledSubAgent(name="analysis", description="Spatial analysis",
            runnable=_mk_agent(model, get_spatial_analysis_job_tools(), SPATIAL_ANALYSIS_PROMPT)),
        CompiledSubAgent(name="map_publish", description="Map decoration",
            runnable=_mk_agent(model, get_map_decoration_job_tools(), MAP_DECORATION_PROMPT)),
    ]


def build_subagents_A(model):
    """Ablation A: Merge layer_loader + analysis -> 4 sub-agents"""
    seen, merged = set(), []
    for t in get_layer_loader_job_tools() + get_spatial_analysis_job_tools():
        if t.name not in seen:
            seen.add(t.name); merged.append(t)
    merged_prompt = (LAYER_LOADER_PROMPT
                     + "\n\nAdditionally, you also take on the following spatial analysis responsibilities:\n" + SPATIAL_ANALYSIS_PROMPT)
    return [
        _sub_event(model), _sub_geocode(model),
        CompiledSubAgent(name="geo_processing", description="Layer loading + spatial analysis (merged)",
            runnable=_mk_agent(model, merged, merged_prompt)),
        CompiledSubAgent(name="map_publish", description="Map decoration",
            runnable=_mk_agent(model, get_map_decoration_job_tools(), MAP_DECORATION_PROMPT)),
    ]


def build_subagents_C(model):
    """Ablation C (v2): Natural language inter-agent communication.

    Differences from control (two layers of change, both necessary):
    1. Tool return values changed from dict to natural language prose (_wrap_tools_nl)
       -> Sub-agent LLM sees prose instead of structured fields
    2. Remove inspect_connectivity_job_tool from supervisor tools
       -> Supervisor cannot obtain structured state via object store
       -> Can only obtain state from the natural language return messages of sub-agents

    The old Ablation C only changed layer 1, the object store was still working, and the supervisor
    could still obtain structured state via inspect, thus no significant difference from control.
    v2 changes both layers simultaneously, which is what the reviewer asked about:
    "JSON vs natural-language inter-agent communication".
    """
    return [
        CompiledSubAgent(name="event_extract", description="Event extraction",
            runnable=_mk_agent(model, _wrap_tools_nl([parse_doc_tool]), EVENT_EXTRACT_PROMPT)),
        CompiledSubAgent(name="geocode", description="Geocoding",
            runnable=_mk_agent(model, _wrap_tools_nl([find_file_by_name_tool, update_airway_coordinates_tool]), GEOCODE_PROMPT)),
        CompiledSubAgent(name="layer_loader", description="Layer loading",
            runnable=_mk_agent(model, _wrap_tools_nl(get_layer_loader_job_tools()), LAYER_LOADER_PROMPT)),
        CompiledSubAgent(name="analysis", description="Spatial analysis",
            runnable=_mk_agent(model, _wrap_tools_nl(get_spatial_analysis_job_tools()), SPATIAL_ANALYSIS_PROMPT)),
        CompiledSubAgent(name="map_publish", description="Map decoration",
            runnable=_mk_agent(model, _wrap_tools_nl(get_map_decoration_job_tools()), MAP_DECORATION_PROMPT)),
    ]


