# ==================================================================
# Inter-run cleanup: avoid _JOB_STORE and QGIS project state contamination across runs
# ==================================================================
def _cleanup_before_run():
    # 1. Clear domap global job store
    _rjs._JOB_STORE.clear()
    # 2. Remove layers and layouts left over from the previous run in QGIS project
    try:
        from qgis.core import QgsProject, QgsLayoutManager
        from qgis.utils import iface
        prj = QgsProject.instance()
        if prj:
            # Remove all layers
            prj.removeAllMapLayers()
            # Remove all layouts
            lm = prj.layoutManager()
            for lo in list(lm.layouts()):
                lm.removeLayout(lo)
        # Refresh canvas
        if iface and iface.mapCanvas():
            iface.mapCanvas().refreshAllLayers()
    except Exception:
        pass


# ==================================================================
# Single run
# ==================================================================
def run_one(variant: str, run_idx: int) -> Dict[str, Any]:
    _cleanup_before_run()
    model = build_model()
    agent, is_single = build_agent_for_variant(variant, model)
    cfg = _build_cfg()
    input_data = {"messages": [{"role": "user", "content": _build_user_task(cfg)}]}

    rec = {"variant": variant, "run_idx": run_idx, "is_single_agent": is_single,
           "start_time": datetime.now().isoformat(timespec="seconds")}
    t0 = time.time()
    success, error, metrics = False, "", {}
    # single_serial: limit ToolNode thread pool to single thread, so multiple tool_calls
    # in the same round execute sequentially. Used to test whether single-agent failures
    # stem from parallel calls to state-dependent tools.
    stream_cfg = {"max_concurrency": 1} if variant == "single_serial" else None
    try:
        chunks = []
        for chunk in agent.stream(input_data, stream_mode="updates", config=stream_cfg):
            chunks.append(chunk)
        metrics = _collect_metrics(chunks)
        success = metrics.get("produced_analysis") or metrics.get("produced_layout")
    except Exception as e:
        error = f"{type(e).__name__}: {e}\n{traceback.format_exc()}"
    finally:
        # B_no_store's monkey-patch contaminates module-level global state,
        # must be restored after each run, otherwise all subsequent variants are invalidated.
        if variant == "B_no_store":
            _restore_store()
    rec.update({"elapsed_sec": round(time.time() - t0, 2),
                "success": bool(success), "error": error[:4000], "metrics": metrics})
    return rec


