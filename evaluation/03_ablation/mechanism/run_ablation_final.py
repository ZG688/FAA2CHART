_GUARD_MARKERS = [
    "must use inspect_connectivity_job_tool",
    "after completion must use inspect_connectivity_job_tool",
    "before entering create_connectivity_job_tool, must call choose_final_json_path_tool",
    "before publish_create_layout_tool succeeds, forbid calling any other layout tools",
    "before publish_create_layout_tool succeeds, do not call other layout tools",
]


def _strip_guard_lines(prompt: str) -> str:
    return "\n".join(l for l in prompt.splitlines()
                     if not any(m in l for m in _GUARD_MARKERS))


def _drop_inspect_and_validate(tools: List) -> List:
    banned = {"inspect_connectivity_job_tool", "loader_validate_inputs_tool"}
    return [t for t in tools if getattr(t, "name", "") not in banned]


