# Exact-match to_id (no Levenshtein, to avoid full-table scan)
def to_id(name, cg):
    n = norm(name)
    if not n:
        return "", False
    if n in cg["ids"]:
        return n, True
    if n in cg["name2id"]:
        return cg["name2id"][n], True
    n2 = re.sub(r"(NDB|VOR|DME|VORTAC|TACAN|WP|FIX)+$", "", n)
    if n2 and n2 in cg["name2id"]:
        return cg["name2id"][n2], True
    return "", False

