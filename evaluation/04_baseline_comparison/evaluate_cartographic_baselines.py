# ============================================================ Load generated layers
def _wkb_linestring_pts(blob):
    if not blob or len(blob) < 9:
        return None
    flags = blob[3]
    env_flag = (flags >> 1) & 0x07
    env_sizes = {0: 0, 1: 32, 2: 48, 3: 48, 4: 64}
    wkb = blob[8 + env_sizes[env_flag]:]
    bo = "<" if wkb[0] == 1 else ">"
    gtype = struct.unpack(bo + "I", wkb[1:5])[0]
    if gtype != 2:
        return None
    npt = struct.unpack(bo + "I", wkb[5:9])[0]
    pts, off = [], 9
    for _ in range(npt):
        x, y = struct.unpack(bo + "dd", wkb[off:off + 16])
        pts.append((x, y))
        off += 16
    return pts


def load_pred_segments(gpkg):
    c = sqlite3.connect(gpkg)
    cols = [x[1] for x in c.execute("PRAGMA table_info('airway_segments')")]
    segs = defaultdict(list)
    for row in c.execute("select * from airway_segments"):
        d = dict(zip(cols, row))
        pts = _wkb_linestring_pts(d["geom"]) if d.get("geom") else None
        if not pts:
            try:
                pts = [(float(d["from_lon"]), float(d["from_lat"])),
                       (float(d["to_lon"]), float(d["to_lat"]))]
            except (TypeError, ValueError):
                continue
        segs[norm(d["airway"])].append(dict(
            airway=norm(d["airway"]),
            from_name=d.get("from_name"), to_name=d.get("to_name"),
            from_type=d.get("from_type"), to_type=d.get("to_type"),
            MEA=norm_alt(d.get("MEA")), MAA=norm_alt(d.get("MAA")),
            pts=pts))
    c.close()
    return segs


# ============================================================ Official gold edges
def build_gold_edges(feb_csv, coord_gold):
    seg = find_csv(feb_csv, "AWY_SEG_ALT.csv")
    rows_by = defaultdict(list)
    with open(seg, encoding="utf-8-sig", newline="") as f:
        for r in csv.DictReader(f):
            rows_by[norm(r["AWY_ID"])].append(r)
    edges = defaultdict(list)
    for aid, rows in rows_by.items():
        def sk(x):
            try: return int(x.get("POINT_SEQ") or 0)
            except ValueError: return 0
        rows.sort(key=sk)
        for x in rows:
            u = norm(x.get("FROM_POINT"))
            v = norm(x.get("TO_POINT"))
            if not u or not v: continue
            u_id, _ = to_id(u, coord_gold)
            v_id, _ = to_id(v, coord_gold)
            def _f(v):
                try: return float(v)
                except (TypeError, ValueError): return None
            edges[aid].append(dict(
                u=u_id, v=v_id,
                mea=norm_alt(x.get("MIN_ENROUTE_ALT")),
                maa=norm_alt(x.get("MAX_AUTH_ALT")),
                mag_course=_f(x.get("MAG_COURSE")),
                dist_nm=_f(x.get("MAG_COURSE_DIST")),
                u_ll=coord_gold["coord"].get(u_id),
                v_ll=coord_gold["coord"].get(v_id)))
    return edges


def load_magvar(csv_dir):
    mv = {}
    nav = find_csv(csv_dir, "NAV_BASE.csv")
    if nav:
        with open(nav, encoding="utf-8-sig", newline="") as f:
            for r in csv.DictReader(f):
                nid = norm(r["NAV_ID"])
                raw = (r.get("MAG_VARN") or "").strip()
                if not raw: continue
                m = re.match(r"(\d+(?:\.\d+)?)\s*([EW]?)", raw)
                if not m: continue
                val = float(m.group(1))
                hemi = m.group(2) or (r.get("MAG_VARN_HEMIS") or "E")
                mv.setdefault(nid, val if hemi == "E" else -val)
    return mv


def initial_bearing_deg(lat1, lon1, lat2, lon2):
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dl = math.radians(lon2 - lon1)
    y = math.sin(dl) * math.cos(p2)
    x = math.cos(p1) * math.sin(p2) - math.sin(p1) * math.cos(p2) * math.cos(dl)
    return (math.degrees(math.atan2(y, x)) + 360.0) % 360.0


def ang_diff(a, b):
    d = abs((a - b) % 360.0)
    return min(d, 360.0 - d)


def seg_endpoint_dist_km(pred_edge, gold_edge):
    if not gold_edge["u_ll"] or not gold_edge["v_ll"]:
        return None
    p0, p1 = pred_edge["pts"][0], pred_edge["pts"][-1]
    gu, gv = gold_edge["u_ll"], gold_edge["v_ll"]
    d_fwd = (haversine_km(p0[1], p0[0], gu[0], gu[1]) +
             haversine_km(p1[1], p1[0], gv[0], gv[1])) / 2
    d_rev = (haversine_km(p0[1], p0[0], gv[0], gv[1]) +
             haversine_km(p1[1], p1[0], gu[0], gu[1])) / 2
    return min(d_fwd, d_rev)


def buffered_iou(pred_edge, gold_edge, buffer_km):
    d = seg_endpoint_dist_km(pred_edge, gold_edge)
    if d is None: return None
    r = buffer_km
    overlap = max(0.0, 1.0 - d / (2.0 * r))
    return overlap / (2.0 - overlap) if overlap > 0 else 0.0


# ============================================================ Single-airway evaluation
def eval_airway(aid, pred_edges, gold_edges, buffer_km):
    def uv(a, b): return tuple(sorted((a, b)))
    gold_set = {uv(e["u"], e["v"]) for e in gold_edges if e["u"] and e["v"]}
    gold_by_key = {}
    for e in gold_edges:
        if e["u"] and e["v"]:
            gold_by_key.setdefault(uv(e["u"], e["v"]), e)
    pred_set, pred_by_key = set(), {}
    for pe in pred_edges:
        pu, _ = to_id(pe["from_name"], CG)
        pv, _ = to_id(pe["to_name"], CG)
        if not pu or not pv: continue
        k = uv(pu, pv)
        pred_set.add(k)
        pred_by_key.setdefault(k, pe)
    gold_nodes = {e["u"] for e in gold_edges} | {e["v"] for e in gold_edges}
    gold_nodes = {x for x in gold_nodes if x}
    pred_nodes = set()
    for pe in pred_edges:
        for nm in (pe["from_name"], pe["to_name"]):
            i, _ = to_id(nm, CG)
            if i: pred_nodes.add(i)
    tp_edges = pred_set & gold_set
    node_inter = pred_nodes & gold_nodes
    node_union = pred_nodes | gold_nodes
    dists, ious, mea_ok, mea_tot, maa_ok, maa_tot = [], [], 0, 0, 0, 0
    brg_err, len_relerr = [], []
    for k in tp_edges:
        pe, ge = pred_by_key[k], gold_by_key[k]
        d = seg_endpoint_dist_km(pe, ge)
        if d is not None:
            dists.append(d)
            iou = buffered_iou(pe, ge, buffer_km)
            if iou is not None: ious.append(iou)
        p0, p1 = pe['pts'][0], pe['pts'][-1]
        if ge.get('mag_course') is not None and ge['u_ll'] and ge['v_ll']:
            d0u = haversine_km(p0[1], p0[0], ge['u_ll'][0], ge['u_ll'][1])
            d0v = haversine_km(p0[1], p0[0], ge['v_ll'][0], ge['v_ll'][1])
            a, b = (p0, p1) if d0u <= d0v else (p1, p0)
            tn = initial_bearing_deg(a[1], a[0], b[1], b[0])
            mv = MAGVAR.get(ge['u'])
            if mv is None: mv = MAGVAR.get(ge['v'], 0.0)
            mag_pred = (tn - mv) % 360.0
            brg_err.append(ang_diff(mag_pred, ge['mag_course']))
        if ge.get('dist_nm') and ge['dist_nm'] > 0:
            dist_km = haversine_km(p0[1], p0[0], p1[1], p1[0])
            dist_nm_pred = dist_km / 1.852
            len_relerr.append(abs(dist_nm_pred - ge['dist_nm']) / ge['dist_nm'])
        if ge["mea"]:
            mea_tot += 1
            if pe["MEA"] == ge["mea"]: mea_ok += 1
        if ge["maa"]:
            maa_tot += 1
            if pe["MAA"] == ge["maa"]: maa_ok += 1
    return dict(aid=aid, edge_tp=len(tp_edges), edge_pred=len(pred_set),
                edge_gold=len(gold_set), node_inter=len(node_inter),
                node_union=len(node_union), dists=dists, ious=ious,
                brg_err=brg_err, len_relerr=len_relerr,
                mea_ok=mea_ok, mea_tot=mea_tot, maa_ok=maa_ok, maa_tot=maa_tot)


# ============================================================ Aggregation + bootstrap
def summarize(per, boot=1000, seed=42):
    def agg(sub):
        etp = sum(x["edge_tp"] for x in sub)
        ep = sum(x["edge_pred"] for x in sub)
        eg = sum(x["edge_gold"] for x in sub)
        ni = sum(x["node_inter"] for x in sub)
        nu = sum(x["node_union"] for x in sub)
        P = etp / ep if ep else 0.0
        R = etp / eg if eg else 0.0
        F1 = 2 * P * R / (P + R) if (P + R) else 0.0
        jac = ni / nu if nu else 0.0
        return P, R, F1, jac
    P, R, F1, jac = agg(per)
    all_d = sorted(d for x in per for d in x["dists"])
    all_i = [i for x in per for i in x["ious"]]
    all_brg = sorted(e for x in per for e in x["brg_err"])
    all_lre = sorted(e for x in per for e in x["len_relerr"])
    mea_ok = sum(x["mea_ok"] for x in per)
    mea_tot = sum(x["mea_tot"] for x in per)
    maa_ok = sum(x["maa_ok"] for x in per)
    maa_tot = sum(x["maa_tot"] for x in per)
    def pct(v, q):
        if not v: return None
        k = min(len(v) - 1, int(q * (len(v) - 1)))
        return v[k]
    rng = random.Random(seed)
    n = len(per)
    bs_F1, bs_jac, bs_med, bs_iou, bs_brg = [], [], [], [], []
    for _ in range(boot):
        sample = [per[rng.randrange(n)] for _ in range(n)]
        _, _, f1b, jacb = agg(sample)
        bs_F1.append(f1b); bs_jac.append(jacb)
        dd = sorted(d for x in sample for d in x["dists"])
        bs_med.append(pct(dd, 0.5) if dd else 0.0)
        ii = [i for x in sample for i in x["ious"]]
        bs_iou.append(sum(ii) / len(ii) if ii else 0.0)
        bb = sorted(e for x in sample for e in x["brg_err"])
        bs_brg.append(pct(bb, 0.5) if bb else 0.0)
    def ci(v):
        v = sorted(v)
        return [round(v[int(0.025 * len(v))], 4), round(v[int(0.975 * len(v)) - 1], 4)]
    return dict(
        n_airways=n,
        edge_P=round(P, 4), edge_R=round(R, 4), edge_F1=round(F1, 4),
        node_jaccard=round(jac, 4),
        matched_edges=len(all_d),
        endpoint_dist_km_median=round(pct(all_d, 0.5), 4) if all_d else None,
        endpoint_dist_km_p95=round(pct(all_d, 0.95), 4) if all_d else None,
        buffered_iou_mean=round(sum(all_i) / len(all_i), 4) if all_i else None,
        MEA_match=round(mea_ok / mea_tot, 4) if mea_tot else None,
        MAA_match=round(maa_ok / maa_tot, 4) if maa_tot else None,
        MEA_n=mea_tot, MAA_n=maa_tot,
        indep_n_bearing=len(all_brg), indep_n_length=len(all_lre),
        bearing_err_deg_median=round(pct(all_brg, 0.5), 3) if all_brg else None,
        bearing_err_deg_p90=round(pct(all_brg, 0.90), 3) if all_brg else None,
        bearing_within_5deg=round(sum(1 for e in all_brg if e <= 5) / len(all_brg), 4) if all_brg else None,
        length_relerr_median=round(pct(all_lre, 0.5), 4) if all_lre else None,
        length_within_5pct=round(sum(1 for e in all_lre if e <= 0.05) / len(all_lre), 4) if all_lre else None,
        ci95=dict(edge_F1=ci(bs_F1), node_jaccard=ci(bs_jac),
                  endpoint_dist_km_median=ci(bs_med),
                  buffered_iou_mean=ci(bs_iou),
                  bearing_err_deg_median=ci(bs_brg)))


# ============================================================ Main flow
def main():
    global CG, MAGVAR
    print("Loading official gold standard ...")
    CG = load_coords(NOV_CSV)
    MAGVAR = load_magvar(FEB_CSV)
    feb_coord = load_coords(FEB_CSV)
    gold_edges = build_gold_edges(FEB_CSV, feb_coord)
    for aid, es in gold_edges.items():
        for e in es:
            e["u_ll"] = CG["coord"].get(e["u"], e["u_ll"])
            e["v_ll"] = CG["coord"].get(e["v"], e["v_ll"])
    n_gold_original = sum(len(v) for v in gold_edges.values())
    print(f"  Official airways: {len(gold_edges)}, official edges (full set): {n_gold_original}")

    # ---- Collect PDF reachable point set: union of official IDs appearing in predictions of all methods ----
    print("\nCollecting PDF reachable point set ...")
    pdf_reachable_ids = set()
    for name, fn in TARGETS:
        gpkg = os.path.join(GPKG_DIR, fn)
        if not os.path.exists(gpkg):
            continue
        pred = load_pred_segments(gpkg)
        for aid, segs in pred.items():
            for pe in segs:
                for nm in (pe["from_name"], pe["to_name"]):
                    i, _ = to_id(nm, CG)
                    if i:
                        pdf_reachable_ids.add(i)
    print(f"  PDF reachable points (union of all methods): {len(pdf_reachable_ids)}")

    # ---- Filter gold edges: keep only those whose both endpoints are in the PDF reachable set ----
    gold_edges_reachable = {}
    n_gold_reachable = 0
    n_gold_filtered_out = 0
    for aid, edges in gold_edges.items():
        filtered = []
        for e in edges:
            if e["u"] and e["v"] and e["u"] in pdf_reachable_ids and e["v"] in pdf_reachable_ids:
                filtered.append(e)
            else:
                n_gold_filtered_out += 1
        if filtered:
            gold_edges_reachable[aid] = filtered
            n_gold_reachable += len(filtered)
    print(f"  PDF reachable edges: {n_gold_reachable} (filtered out {n_gold_filtered_out} edges whose endpoints are not on PDF)")
    print(f"  Reachable rate: {n_gold_reachable}/{n_gold_original} = {n_gold_reachable/n_gold_original:.1%}")

    report = {}
    for name, fn in TARGETS:
        gpkg = os.path.join(GPKG_DIR, fn)
        if not os.path.exists(gpkg):
            print(f"  [Warning] Not found: {gpkg}")
            continue
        print(f"\nEvaluating {name} ...")
        pred = load_pred_segments(gpkg)
        print(f"  Generated airways: {len(pred)}, generated edges: {sum(len(v) for v in pred.values())}")
        # Evaluate using PDF-reachable gold
        common = [a for a in pred if a in gold_edges_reachable]
        print(f"  Comparable airways (intersection): {len(common)}")
        per = [eval_airway(a, pred[a], gold_edges_reachable[a], 5.0) for a in common]
        per = [x for x in per if x["edge_gold"] > 0]
        s = summarize(per)
        # Also compute full-set R (using original gold edge count as denominator)
        n_tp = sum(x["edge_tp"] for x in per)
        s["edge_R_full"] = round(n_tp / n_gold_original, 4) if n_gold_original else 0.0
        s["n_gold_original"] = n_gold_original
        s["n_gold_reachable"] = n_gold_reachable
        report[name] = s
        print(f"  edge_F1(adj)={s['edge_F1']:.4f}  edge_R(adj)={s['edge_R']:.4f}  "
              f"edge_R(full)={s['edge_R_full']:.4f}  "
              f"node_jac={s['node_jaccard']:.4f}  "
              f"brg_err={s['bearing_err_deg_median']}°  len_err={s['length_relerr_median']}")

    # Cross-comparison table
    print(f"\n{'=' * 130}")
    print(f"{'Model':<14} {'edge_P':>7} {'R(adj)':>7} {'R(full)':>7} {'F1(adj)':>8} {'F1(full)':>8} "
          f"{'node_J':>7} {'brg_err':>7} {'len_err':>7} {'n_edges':>7} {'gold_adj':>7} {'gold_full':>7}")
    print(f"{'-' * 130}")
    for name, _ in TARGETS:
        if name not in report: continue
        s = report[name]
        def f(v, nd=3):
            return f"{v:.{nd}f}" if v is not None else "  n/a"
        f1_full = 2 * s['edge_P'] * s['edge_R_full'] / (s['edge_P'] + s['edge_R_full']) if (s['edge_P'] + s['edge_R_full']) else 0.0
        print(f"{name:<14} {f(s['edge_P'])} {f(s['edge_R'])} {f(s['edge_R_full'])} "
              f"{f(s['edge_F1']):>8} {f(f1_full):>8} "
              f"{f(s['node_jaccard'])} {f(s['bearing_err_deg_median'],1):>7} "
              f"{f(s['length_relerr_median'])} {s['matched_edges']:>7} "
              f"{s['n_gold_reachable']:>7} {s['n_gold_original']:>7}")

    # Save JSON
    out = {
        "meta": {
            "gold_topology": "Feb-2025 NASR AWY_SEG_ALT",
            "gold_geometry": "Nov-2025 NASR (contemporaneous with the navigation database used for generated layer toponym geolocation)",
            "buffer_km": 5.0,
            "n_gold_original": n_gold_original,
            "n_gold_reachable": n_gold_reachable,
            "pdf_reachable_rate": round(n_gold_reachable / n_gold_original, 4),
            "note": "All methods use the same cartographic pipeline (JSON -> coordinate lookup -> WKB LINESTRING -> GPKG); cartographic quality differences arise entirely from extraction quality differences",
            "note_reachable": "R(adj)/F1(adj) use PDF-reachable edges as denominator (only count edges whose both endpoints appear in the PDF), eliminating reference frame mismatch caused by FAA selective charting; R(full)/F1(full) use the full NASR set as denominator for reference",
        },
        "results": report,
    }
    json.dump(out, open(OUT_JSON, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"\nResults saved to: {OUT_JSON}")


if __name__ == "__main__":
    main()