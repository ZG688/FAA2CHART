# -*- coding: utf-8 -*-
"""
Generate GPKG from extraction JSONs (pure Python, no QGIS/GDAL dependency)
==================================================================
Convert each method's (FAA2CHART + 6 baselines) parsed_routes_*.json into
airway_segments GPKG for evaluation by evaluate_cartographic.py.

GPKG schema is consistent with faa_airways_visualization.gpkg generated by FAA2CHART:
  airway_segments(airway, from_name, to_name, from_type, to_type,
                  MEA, MAA, from_lon, from_lat, to_lon, to_lat, geom)

Coordinate source: Nov-2025 NASR (same geometric reference as evaluate_cartographic.py).
Point localization: reuses to_id + load_coords from evaluate_extraction_v2, identical calibration.
"""
import os, sys, json, struct, sqlite3, re

HERE = os.path.dirname(os.path.abspath(__file__))
TIERA_DIR = os.path.normpath(os.path.join(
    HERE, "..", "..", "01_extraction", "TierA"))
sys.path.insert(0, TIERA_DIR)
from evaluate_extraction_v2 import norm, norm_alt, load_coords, find_csv

# Exact match + alias mapping (no Levenshtein, avoid full table scan)
def to_id(name, cg):
    n = norm(name)
    if not n:
        return "", False
    if n in cg["ids"]:
        return n, True
    if n in cg["name2id"]:
        return cg["name2id"][n], True
    n2 = re.sub(r"(NDB|VOR|DME|VORTAC|TACAN|WP|FIX)+$", "", n)
    if n2 and n2 in cg["name2id"]:
        return cg["name2id"][n2], True
    return "", False

PRED_DIR = os.environ.get("FAA2CHART_PRED_DIR", "PATH_TO_YOUR_PRED_DIR")
NOV_CSV = os.environ.get("FAA2CHART_NOV_CSV_DIR", "PATH_TO_YOUR_NOV_CSV_DIR")
OUT_DIR = os.path.join(HERE, "..", "eval_results", "baselines_gpkg")
os.makedirs(OUT_DIR, exist_ok=True)

TARGETS = {
    "FAA2CHART":  "parsed_routes_newnew_5_deepseek_chat_updated_merged.json",
    "Rule-based": "parsed_routes_baseline_rule_based.json",
    "RAG":        "parsed_routes_baseline_rag.json",
    "Codegen":    "parsed_routes_baseline_codegen.json",
    "ReAct":      "parsed_routes_baseline_react.json",
    "AutoGen":    "parsed_routes_baseline_autogen.json",
}


def wkb_linestring(pts):
    """Generate WKB LINESTRING. pts = [(lon, lat), ...]"""
    n = len(pts)
    if n < 2:
        return None
    buf = bytearray()
    buf += struct.pack("<B", 1)           # little-endian
    buf += struct.pack("<I", 2)           # LINESTRING
    buf += struct.pack("<I", n)           # num points
    for x, y in pts:
        buf += struct.pack("<dd", x, y)   # lon, lat
    return bytes(buf)


def make_gpkg(name, json_path, cg, out_path):
    """Generate GPKG from JSON."""
    data = json.load(open(json_path, encoding="utf-8"))
    # Delete old file
    if os.path.exists(out_path):
        os.remove(out_path)
    c = sqlite3.connect(out_path)
    c.execute("""CREATE TABLE airway_segments (
        airway TEXT, from_name TEXT, to_name TEXT,
        from_type TEXT, to_type TEXT,
        MEA TEXT, MAA TEXT,
        from_lon REAL, from_lat REAL, to_lon REAL, to_lat REAL,
        geom BLOB)""")

    n_segs = 0
    n_skip = 0
    for item in data:
        code = norm(item.get("airway_code", ""))
        if not code or code.startswith("NONETABLE") or code.startswith("NONETEXT"):
            continue
        pts = item.get("airway_point", [])
        if len(pts) < 2:
            continue
        # Construct edges segment by segment
        for i in range(len(pts) - 1):
            p0, p1 = pts[i], pts[i + 1]
            n0, n1 = norm(p0.get("name", "")), norm(p1.get("name", ""))
            if not n0 or not n1:
                continue
            id0, _ = to_id(p0.get("name", ""), cg)
            id1, _ = to_id(p1.get("name", ""), cg)
            ll0 = cg["coord"].get(id0)
            ll1 = cg["coord"].get(id1)
            if not ll0 or not ll1:
                n_skip += 1
                continue
            # WKB: (lon, lat)
            wkb = wkb_linestring([(ll0[1], ll0[0]), (ll1[1], ll1[0])])
            if wkb is None:
                continue
            mea = norm_alt(p0.get("MEA", ""))
            maa = norm_alt(p0.get("MAA", ""))
            c.execute(
                "INSERT INTO airway_segments VALUES (?,?,?,?,?,?,?,?,?,?,?,?)",
                (code, n0, n1,
                 p0.get("type", ""), p1.get("type", ""),
                 mea, maa,
                 ll0[1], ll0[0], ll1[1], ll1[0], wkb))
            n_segs += 1
    c.commit()
    c.close()
    print(f"  {name}: {n_segs} segments, skipped {n_skip} (no coords)")
    return n_segs


def main():
    print("Loading Nov-2025 NASR coordinate library...")
    cg = load_coords(NOV_CSV)
    print(f"  Coordinate library: {len(cg['coord'])} ids")

    results = {}
    for name, fn in TARGETS.items():
        path = os.path.join(PRED_DIR, fn)
        if not os.path.exists(path):
            print(f"  [WARNING] Not found: {path}")
            continue
        out = os.path.join(OUT_DIR, f"airway_segments_{name.replace(' ', '_')}.gpkg")
        n = make_gpkg(name, path, cg, out)
        results[name] = dict(path=out, n_segs=n)

    print(f"\nGPKG generation complete, output directory: {OUT_DIR}")
    for name, info in results.items():
        print(f"  {name}: {info['path']}")


if __name__ == "__main__":
    main()